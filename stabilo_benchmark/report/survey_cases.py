"""
survey_cases.py - The cases a survey selected, as a table: `stabilo-benchmark report SURVEY.json`.

One row per selected case, in cell order: its cell, its reference frame, the descriptors it was
placed on (moving foreground and coherence, stationarity for the control) and how many objects the
reference frame holds. The caption states the pool, how a candidate was read, the splits and any
cell that could not be filled, from what the SURVEY.json records and the survey's thresholds.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Mapping

SURVEY_FILE = 'SURVEY.json'
CELL_ORDER = (
    'high moving / coherent',
    'high moving / mixed',
    'low moving / coherent',
    'low moving / mixed',
    'stationary control',
)

CAPTION = (
    'Part II: the cases, selected from {pool} of {day}. {anchor} '
    'Each candidate is read on pairs of its reference frame with the frames {offsets} frames later. Moving: the '
    'share of the frame covered by reference-frame objects displaced by more than {displaced} median object widths; '
    'Coherence: the share of that foreground moving with one of them (within {coherent} widths or {share} '
    'of its displacement, whichever is larger); Stationarity: the share of the found foreground that stayed '
    'in place; each averaged over the offsets. Cells split at the pool medians (moving {moving:.2f}\\%, '
    'coherence {coherence:.2f}); coherence is undefined below {min_objects} displaced objects, which left '
    '{n_unclassified} candidates unclassified, and the control comes from the top decile of stationarity. '
    'Reference: the reference frame\'s index in its recording; Objects: its detections. {unfilled}'
)


def is_survey_file(path: Path) -> bool:
    """Whether `path` is a survey's SURVEY.json rather than a results directory."""
    return Path(path).is_file() and Path(path).name == SURVEY_FILE


def case_rows(survey: Mapping[str, Any]) -> List[Dict[str, Any]]:
    """The selected cases, in cell order, each with its day-qualified name."""
    rank = {cell: i for i, cell in enumerate(CELL_ORDER)}
    rows = []
    for candidate in survey['selection']['selected']:
        parts = str(candidate.get('source', '')).split('/')
        day = next((p for p in parts if len(p) == 10 and p[4] == '-' and p[7] == '-'), '')
        rows.append({**candidate, 'case': f"{day}_{candidate['video']}" if day else candidate['video'], 'day': day})
    return sorted(rows, key=lambda row: rank.get(row.get('cell', ''), len(rank)))


def _number(value: Any, fmt: str) -> str:
    try:
        value = float(value)
    except (TypeError, ValueError):
        return '--'
    return '--' if value != value else fmt.format(value)


def write_cases_table(survey: Mapping[str, Any], path: Path, label: str = 'tab:survey-cases') -> Path:
    """The selected cases as one booktabs table."""
    rows = case_rows(survey)
    strata = survey.get('strata') or {}
    splits = strata.get('splits') or {}
    unfilled = (survey.get('selection') or {}).get('unfilled') or {}
    unfilled_note = (
        'Cells left short: ' + ', '.join(f"{cell} ({count})" for cell, count in unfilled.items()) + '.'
        if unfilled
        else 'Every cell was filled.'
    )
    thresholds = survey.get('thresholds')
    if not isinstance(thresholds, dict):
        raise ValueError('The survey records no thresholds; rerun it with this version of stabilo-benchmark')

    days = sorted({row['day'] for row in rows if row['day']})
    n_candidates = survey.get('n_candidates', len(survey.get('candidates') or []))
    recordings = {c.get('video') for c in survey.get('candidates') or []}
    caption = CAPTION.format(
        pool=_pool(n_candidates, len(recordings)),
        day=', '.join(days) or 'the pool',
        anchor=_anchor_note(survey),
        offsets=_series(survey.get('offsets') or []),
        displaced=f"{thresholds['displaced_widths']:g}",
        coherent=f"{thresholds['coherent_widths']:g}",
        share=f"{thresholds['coherent_share']:.0%}".replace('%', '\\%'),
        min_objects=thresholds['min_displaced_objects'],
        moving=100 * float(splits.get('moving', float('nan'))),
        coherence=float(splits.get('coherence', float('nan'))),
        n_unclassified=len((strata.get('cells') or {}).get('unclassified') or []),
        unfilled=unfilled_note,
    )
    lines = [
        '% Generated by stabilo-benchmark report; do not edit by hand.',
        r'\begin{table}[htbp]',
        r'  \centering',
        f"  \\caption{{{caption}}}",
        f"  \\label{{{label}}}",
        r'  \small',
        r'  \begin{tabular}{llrrrrr}',
        r'    \toprule',
        r'    Case & Cell & Reference & Moving [\%] & Coherence & Stationarity & Objects \\',
        r'    \midrule',
    ]
    for row in rows:
        name = row['case'].replace('_', r'\_')
        lines.append(
            f"    {name} & {row.get('cell', '')} & {_number(row.get('frame'), '{:.0f}')} & "
            f"{_number(100 * float(row.get('displaced', 'nan')), '{:.2f}')} & "
            f"{_number(row.get('coherence'), '{:.2f}')} & {_number(row.get('stationarity'), '{:.2f}')} & "
            f"{_number(row.get('n_objects'), '{:.0f}')} \\\\"
        )
    lines += [r'    \bottomrule', r'  \end{tabular}', r'\end{table}', '']
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines), encoding='utf-8')
    return path


def _pool(n_candidates: int, n_recordings: int) -> str:
    """'405 hovers', or '831 candidate reference frames in 370 hovers' when a hover held several."""
    if n_recordings in (0, n_candidates):
        return f"{n_candidates} hovers"
    return f"{n_candidates} candidate reference frames in {n_recordings} hovers"


def _anchor_note(survey: Mapping[str, Any]) -> str:
    """How the candidate reference frames were placed in a recording."""
    if survey.get('anchor') == 'scan':
        return (
            f"Candidates are points every {survey.get('scan_stride')} frames inside each hover, clear of its "
            f"first and last seconds, and a case's reference frame is its selected point; a hover supplies "
            f"at most one case."
        )
    return 'Each case is one hover referenced at its first frame.'


def _series(values: List[Any]) -> str:
    """'1, 2, 5, 11 and 22'."""
    items = [str(int(v)) for v in values]
    if len(items) < 2:
        return items[0] if items else '--'
    return ', '.join(items[:-1]) + ' and ' + items[-1]


def build_survey_report(survey_path: Path, tables_dir: Path, prefix: str = 'survey') -> Dict[str, Any]:
    """`report` on a SURVEY.json: the cases table."""
    survey = json.loads(Path(survey_path).read_text(encoding='utf-8'))
    table = write_cases_table(survey, Path(tables_dir) / f"{prefix}_cases.tex")
    return {'kind': 'survey', 'tables': [str(table)], 'figures': [], 'skipped': [], 'warnings': []}
